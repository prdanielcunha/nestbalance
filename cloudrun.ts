import express from 'express';
import { rateLimit, requestTelemetry, runtimeIdentity, securityHeaders } from './server/http-runtime.js';
import { commitCapture } from './server/capture.js';
import { finalizeEvidence, startEvidence, uploadEvidence } from './server/evidence.js';
import { analyzeEvidenceText } from './server/evidence-analysis.js';
import { getVaultEvidenceDetail, listVaultEvidence, previewVaultEvidence, searchVaultEvidence } from './server/vault.js';
import { createAccount, updateAccountBalance } from './server/accounts.js';
import { archiveSavingsPot, deleteSavingsPotCover, getSavingsPotDetail, moveSavingsPot, previewSavingsPotCover, syncSavingsPotAutomations, updateSavingsPotAutomation, uploadSavingsPotCover, upsertSavingsPot } from './server/savings-pots.js';
import { createCreditCard } from './server/cards.js';
import { commitCreditCardInvoice, payCreditCardInvoice, previewCreditCardInvoice, reviewCreditCardInvoice } from './server/invoices.js';
import { analyzeCreditCardInvoiceImage } from './server/invoice-vision.js';
import { analyzeEvidenceWithAi } from './server/evidence-ai.js';
import { bootstrapSession } from './server/session.js';
import { getHomeData } from './server/home.js';
import { answerFinanceAssistant } from './server/assistant.js';
import { commitFinancialScreen } from './server/financial-screen.js';
import { findCommitmentPaymentMatches, findCommitmentPaymentMatchesBatch, payCommitment, undoCommitmentPayment } from './server/commitment-payments.js';
import { selectHousehold } from './server/session.js';
import { acceptHouseholdInvite, createHouseholdInvite, getHouseholdSettings, removeHouseholdMember, renameHousehold, revokeHouseholdInvite, updateHouseholdLocale, updateHouseholdMemberRole } from './server/household.js';
import { deleteHousehold, deletePersonalData, exportPrivacyData, getPrivacyStatus, recordPrivacyConsent } from './server/data-rights.js';
import { analyzeRedactedTextWithGemini, getGeminiFallbackStatus } from './server/gemini-fallback.js';
import { confirmRecurringSuggestion, dismissRecurringSuggestion } from './server/recurrences.js';
import { updateTransactionCategory } from './server/categories.js';
import { updateProactivityPreferences } from './server/proactivity.js';
import { dismissAttention } from './server/attention.js';
import { listSecurityDevices, revokeNestBalanceSessions } from './server/security.js';
import { getHouseholdRevision } from './server/revision.js';
import { recordWebVital } from './server/product-metrics.js';

const app = express();
app.disable('x-powered-by');
app.use(securityHeaders);
app.use(requestTelemetry);
const healthz = (_req: express.Request, res: express.Response) => res.json({
  ok:true,
  service:'nestbalance-api',
  ...runtimeIdentity()
});
app.get('/healthz', healthz);
app.get('/api/healthz', healthz);
app.use('/api',rateLimit({windowMs:60_000,max:180,namespace:'api'}));
const sensitiveLimit=rateLimit({windowMs:60_000,max:12,namespace:'sensitive'});
const aiFreeLimit=rateLimit({windowMs:60_000,max:6,namespace:'gemini-free'});
app.post('/api/evidence/upload', express.raw({ type: '*/*', limit: '20mb' }), uploadEvidence);
app.post('/api/savings-pots/cover/upload', express.raw({ type: ['image/jpeg','image/png','image/webp'], limit: '5mb' }), uploadSavingsPotCover);
app.use(express.json({ limit: '128kb' }));
app.post('/api/metrics/web-vital', rateLimit({windowMs:60_000,max:30,namespace:'web-vitals'}), recordWebVital);
app.post('/api/session/bootstrap', bootstrapSession);
app.post('/api/session/select-household', selectHousehold);
app.post('/api/household/settings', getHouseholdSettings);
app.post('/api/household/revision', getHouseholdRevision);
app.post('/api/household/rename', renameHousehold);
app.post('/api/household/locale', updateHouseholdLocale);
app.post('/api/household/invite', sensitiveLimit, createHouseholdInvite);
app.post('/api/household/invite/accept', acceptHouseholdInvite);
app.post('/api/household/invite/revoke', revokeHouseholdInvite);
app.post('/api/household/member/role', sensitiveLimit, updateHouseholdMemberRole);
app.post('/api/household/member/remove', sensitiveLimit, removeHouseholdMember);
app.post('/api/privacy/status', getPrivacyStatus);
app.post('/api/privacy/consent', recordPrivacyConsent);
app.post('/api/privacy/export', sensitiveLimit, exportPrivacyData);
app.post('/api/privacy/delete-personal', sensitiveLimit, deletePersonalData);
app.post('/api/privacy/delete-household', sensitiveLimit, deleteHousehold);
app.post('/api/security/devices', listSecurityDevices);
app.post('/api/security/revoke-sessions', sensitiveLimit, revokeNestBalanceSessions);
app.post('/api/home', getHomeData);
app.post('/api/assistant/answer', answerFinanceAssistant);
app.post('/api/ai/gemini/status', getGeminiFallbackStatus);
app.post('/api/ai/gemini/analyze-text', aiFreeLimit, analyzeRedactedTextWithGemini);
app.post('/api/financial-screen/commit', commitFinancialScreen);
app.post('/api/commitments/match-payment', findCommitmentPaymentMatches);
app.post('/api/commitments/match-payments', findCommitmentPaymentMatchesBatch);
app.post('/api/commitments/pay', payCommitment);
app.post('/api/commitments/undo-payment', undoCommitmentPayment);
app.post('/api/recurrences/confirm', confirmRecurringSuggestion);
app.post('/api/recurrences/dismiss', dismissRecurringSuggestion);
app.post('/api/categories/transaction', updateTransactionCategory);
app.post('/api/member/proactivity-preferences', updateProactivityPreferences);
app.post('/api/attention/dismiss', sensitiveLimit, dismissAttention);
app.post('/api/evidence/start', startEvidence);
app.post('/api/evidence/finalize', finalizeEvidence);
app.post('/api/evidence/analyze-text', analyzeEvidenceText);
app.post('/api/evidence/analyze-ai', analyzeEvidenceWithAi);
app.post('/api/vault/list', listVaultEvidence);
app.post('/api/vault/search', searchVaultEvidence);
app.post('/api/vault/detail', getVaultEvidenceDetail);
app.post('/api/vault/preview', previewVaultEvidence);
app.post('/api/capture/commit', commitCapture);
app.post('/api/accounts/create', createAccount);
app.post('/api/accounts/update-balance', updateAccountBalance);
app.post('/api/savings-pots/upsert', upsertSavingsPot);
app.post('/api/savings-pots/move', moveSavingsPot);
app.post('/api/savings-pots/detail', getSavingsPotDetail);
app.post('/api/savings-pots/archive', archiveSavingsPot);
app.post('/api/savings-pots/automation', updateSavingsPotAutomation);
app.post('/api/savings-pots/automation/sync', syncSavingsPotAutomations);
app.post('/api/savings-pots/cover/preview', previewSavingsPotCover);
app.post('/api/savings-pots/cover/delete', deleteSavingsPotCover);
app.post('/api/cards/create', createCreditCard);
app.post('/api/invoices/preview', previewCreditCardInvoice);
app.post('/api/invoices/review', reviewCreditCardInvoice);
app.post('/api/invoices/analyze-image', analyzeCreditCardInvoiceImage);
app.post('/api/invoices/commit', commitCreditCardInvoice);
app.post('/api/invoices/pay', payCreditCardInvoice);
app.use((_req, res) => res.status(404).json({ ok: false, error: 'NOT_FOUND' }));

const port = Number(process.env.PORT || 8080);
app.listen(port, '0.0.0.0', () => console.log(`nestbalance-api listening on ${port}`));
